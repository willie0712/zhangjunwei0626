function warmupImageConnection() {

  const link =
    document.createElement(
      "link"
    );

  link.rel =
    "preconnect";

  link.href =
    "https://i.ibb.co";

  link.crossOrigin =
    "";

  document.head.appendChild(
    link
  );

}


