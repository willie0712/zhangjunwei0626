/* =========================================================
   HTML ESCAPE
   ========================================================= */

function escapeHTML(value) {

  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");

}


/* =========================================================
   ALBUMS
   ========================================================= */

function renderAlbums() {

  if (!albumGrid) return;

  albumGrid.innerHTML = "";

  albums.forEach((album, index) => {

    const card =
      document.createElement("article");

    card.className =
      "album-card";

    card.dataset.albumId =
      album.id;

    card.tabIndex = 0;

    card.innerHTML = `

      <div class="album-cover">

        <img
          src="${album.cover}"
          alt="${escapeHTML(album.title)}"
          loading="${index === 0 ? "eager" : "lazy"}"
          decoding="async"
        >

        <div class="album-cover-overlay"></div>

        <div class="album-count">
          ${album.photos.length} 張
        </div>

        <div class="album-open-icon">
          →
        </div>

      </div>

      <div class="album-info">

        <h3>
          ${escapeHTML(album.title)}
        </h3>

        <p>
          ${escapeHTML(album.subtitle)}
        </p>

      </div>
    `;

    albumGrid.appendChild(card);

  });


  albumGrid
    .querySelectorAll(".album-card")
    .forEach(card => {

      const open = () => {

        const album =
          albums.find(
            item =>
              item.id ===
              card.dataset.albumId
          );

        if (album) {
          openAlbum(album);
        }

      };


      card.addEventListener(
        "click",
        open
      );


      card.addEventListener(
        "keydown",
        event => {

          if (
            event.key === "Enter" ||
            event.key === " "
          ) {

            event.preventDefault();

            open();

          }

        }
      );

    });


  requestAnimationFrame(() => {

    albumGrid
      .querySelectorAll(".album-card")
      .forEach((card, index) => {

        setTimeout(() => {

          card.classList.add(
            "is-ready"
          );

        }, index * 90);

      });

  });

}


