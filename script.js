/* =========================================================
   KEYBOARD
   ========================================================= */

document.addEventListener(
  "keydown",
  event => {

    if (
      !lightbox ||
      !lightbox.classList.contains(
        "is-open"
      )
    ) {
      return;
    }


    if (
      event.key ===
      "Escape"
    ) {

      closeLightbox();

      return;

    }


    if (
      event.key ===
      "ArrowLeft"
    ) {

      showPreviousPhoto();

    }


    if (
      event.key ===
      "ArrowRight"
    ) {

      showNextPhoto();

    }

  }
);


/* =========================================================
   TOUCH SWIPE
   ========================================================= */

let touchStartX = 0;

let touchStartY = 0;


if (lightbox) {

  lightbox.addEventListener(
    "touchstart",
    event => {

      if (
        event.touches.length !== 1
      ) {
        return;
      }


      touchStartX =
        event.touches[0].clientX;

      touchStartY =
        event.touches[0].clientY;

    },
    {
      passive: true
    }
  );


  lightbox.addEventListener(
    "touchend",
    event => {

      if (
        event.changedTouches.length !== 1
      ) {
        return;
      }


      const endX =
        event.changedTouches[0].clientX;

      const endY =
        event.changedTouches[0].clientY;


      const diffX =
        endX - touchStartX;

      const diffY =
        endY - touchStartY;


      if (
        Math.abs(diffX) < 50
      ) {
        return;
      }


      if (
        Math.abs(diffX) <
        Math.abs(diffY)
      ) {
        return;
      }


      if (diffX > 0) {

        showPreviousPhoto();

      } else {

        showNextPhoto();

      }

    },
    {
      passive: true
    }
  );

}


/* =========================================================
   MOUSE CARD EFFECT
   ========================================================= */

document.addEventListener(
  "mousemove",
  event => {

    const card =
      event.target.closest?.(
        ".album-card"
      );


    if (!card) return;


    const rect =
      card.getBoundingClientRect();


    const x =
      (
        (
          event.clientX -
          rect.left
        ) /
        rect.width -
        0.5
      ) * 2;


    const y =
      (
        (
          event.clientY -
          rect.top
        ) /
        rect.height -
        0.5
      ) * 2;


    card.style.setProperty(
      "--mouse-x",
      x.toFixed(3)
    );


    card.style.setProperty(
      "--mouse-y",
      y.toFixed(3)
    );

  }
);


